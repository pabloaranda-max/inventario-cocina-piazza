w('')
w('No es una conciliación contable definitiva. La única')
w('cifra estimada es el costo de los productos sin')
w('receta; el resto viene directo de Xetux.')
w('')
w(f'Trazabilidad: {T["movimientos"]} transferencias por ${T["transf_total"]:,.0f},')
w('todas con origen, destino, encargado y fecha.')

open(OUT, 'w', encoding='utf-8').write('\n'.join(L) + '\n')
print(f'{os.path.basename(OUT)}  {os.path.getsize(OUT)/1024:.1f} KB  ·  {len(L)} líneas')
