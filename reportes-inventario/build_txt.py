#!/usr/bin/env python3
"""Genera el reporte de costo en texto plano desde las cifras canónicas."""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import datos

OUT = '/home/lilp/proyectos/reporte-costo-julio-2026.txt'
