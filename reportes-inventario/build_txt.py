L = []
w = L.append

w('*COSTO DE INVENTARIO — JULIO 2026*')
w('Piazza Pasticcio · venta 01–31/07/2026')
w('6 de 7 almacenes · SALUMERIA pendiente de reaplicación')
w('')
w(SEP)
w('')
w('*EL COSTO REAL DEL MES*')
w('')
w(f'Costo real de consumo              {T["pct_real"]:6.1f} %')
w(f'Costo teórico, por receta          {T["pct_teo"]:6.1f} %')
w(f'BRECHA                {T["pts"]:4.1f} pts · ${T["brecha"]:>10,.0f}')
w('')
w('El costo real es lo que *salió* del inventario:')
w('inventario inicial más compras, menos lo contado')
w(f'físicamente al cierre. ${T["neto"]:,.0f} sobre ${T["venta"]:,.0f}')
w('de venta atribuida. No depende de las recetas.')
w('')
w('El teórico es lo que las recetas dicen que *debió*')
w('salir por lo vendido. La diferencia es la brecha.')
w('')
w('*La venta atribuida no es la venta del mes.* El mes')
w(f'vendió ${datos.VENTA_POS:,.0f}. La venta atribuida suma')
w(f'${T["venta"]:,.0f}: es la venta de los productos que sí')
w('tienen receta, los únicos que consumen de un almacén.')
